const currentLanguage = ref<SupportedLanguage>('zh-CN')

export function setLanguage(language: SupportedLanguage): void {
  currentLanguage.value = language
  if (typeof document !== 'undefined') {
    document.documentElement.lang = language
  }
}

export function t(key: string): string {
  return dictionaries[currentLanguage.value][key] ?? dictionaries['zh-CN'][key] ?? key
}

export function jobStatusLabel(status: JobStatus): string {
  const keys: Record<string, string> = {
    compatible: 'jobStatusCompatible',
    processing: 'jobStatusProcessing',
    processed: 'jobStatusProcessed',
    failed: 'jobStatusFailed'
  }
  const key = keys[status]
  return key ? t(key) : status
}

export function serviceStatusLabel(status: string): string {
  const keys: Record<string, string> = {
    running: 'serviceStatusRunning',
    restarting: 'serviceStatusRestarting',
    restart_failed: 'serviceStatusRestartFailed'
  }
  const key = keys[status]
  return key ? t(key) : status
}

export function eventStreamStatusLabel(status: EventStreamStatus): string {
  const keys: Record<EventStreamStatus, string> = {
    connecting: 'eventStatusConnecting',
    connected: 'eventStatusConnected',
    disconnected: 'eventStatusDisconnected',
    error: 'eventStatusError'
  }
  return t(keys[status])
}
